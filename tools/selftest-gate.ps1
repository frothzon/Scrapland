#Requires -Version 5.1
<#
.SYNOPSIS
    Proves the headless gate can fail: injects a deliberately failing test, runs the suite,
    asserts exit code 1, then removes the probe and rebuilds.

.DESCRIPTION
    A green suite only means something if a red test actually turns the gate red. Run this after
    changing TestRunner / tools\test.ps1, or when a "passing" result looks suspicious.
#>
[CmdletBinding()]
param()

. (Join-Path $PSScriptRoot 'common.ps1')

$probePath = Join-Path (Get-GodotProjectPath) 'Tests\Headless\Cases\GateSelfCheck.cs'
$log = Join-Path (New-ArtifactsDirectory) 'gate-selftest.log'
$failures = [System.Collections.Generic.List[string]]::new()

$probe = @'
namespace ForagerClone.Tests.Headless.Cases;

/// <summary>Generated by tools\selftest-gate.ps1 - must never be committed.</summary>
[HeadlessTest(Tags = "gate-self-check")]
public partial class GateSelfCheck : HeadlessTest
{
    public override Task RunAsync(HeadlessTestContext context)
    {
        context.AssertEqual(2, 1 + 1 + 1, "deliberate failure: the gate must report this");
        return Task.CompletedTask;
    }
}
'@

try {
    Write-Step 'Injecting a deliberately failing headless test'
    Set-Content -LiteralPath $probePath -Value $probe -Encoding UTF8

    & dotnet build (Join-Path (Get-GodotProjectPath) 'ForagerClone.csproj') -c Debug --nologo | Out-Host
    if ($LASTEXITCODE -ne 0) {
        $failures.Add('probe build failed')
    }
    else {
        $code = Invoke-Godot -Arguments @(
            '--headless',
            '--fixed-fps', '60',
            '--path', (Get-GodotProjectPath),
            '--scene', 'res://Tests/Headless/TestRunner.tscn',
            '--log-file', $log
        ) -UserArguments @('--filter=gate-self-check', '--timeout=60')

        if ($code -ne 1) {
            $failures.Add("expected the gate to exit 1 for a failing test, got $code")
        }
        else {
            Write-Host 'Gate correctly reported the deliberate failure (exit 1).' -ForegroundColor Green
        }
    }
}
finally {
    Write-Step 'Removing the probe and rebuilding'
    Remove-Item -LiteralPath $probePath -Force -ErrorAction SilentlyContinue
    & dotnet build (Join-Path (Get-GodotProjectPath) 'ForagerClone.csproj') -c Debug --nologo | Out-Host
}

Write-Step 'SELFTEST RESULT'
if ($failures.Count -eq 0) {
    Write-Host 'GATE SELFTEST OK' -ForegroundColor Green
    exit 0
}

foreach ($failure in $failures) { Write-Host "FAILED: $failure" -ForegroundColor Red }
exit 1
